// Lanbai / 蓝白 -- LanbaiExposure: the EXPO_UP / EXPO_DOWN weight solver (ART BIBLE v2.1, 1.4 + appendix B2/B3).
//
// UdonSharp 1.x script. UNCOMPILED on the art side (we have no Unity here): it was type-checked with
// Roslyn against stub declarations of UdonSharp / VRC / PPv2, which proves C# syntax and types only,
// NOT the Udon extern whitelist. Check the Class Exposure Tree (VRChat SDK > Udon Sharp) once.
//
// WHY THIS EXISTS
//   PPv2 overrides are "lerp to an ABSOLUTE value": param = lerp(current, volumeValue, weight).
//   A "+1 EV helper" does NOT add 1 EV. So the two exposure helpers carry far targets
//   (EXPO_UP postExposure = +4, EXPO_DOWN = -4) and the Director solves their weight every frame:
//       b   = postExposure already blended by the scene volumes (PPv2 fold, lowest priority first)
//       w   =  dEV / (4 - b)   (dEV > 0, EXPO_UP)
//       w   = -dEV / (b + 4)   (dEV < 0, EXPO_DOWN)
//   Result is exactly b + dEV, and w is linear in dEV, so an EV-linear envelope stays EV-linear.
//   Sum every exposure event of the frame (beat decay + flash + white ramp + mirror pulse) into ONE dEV
//   first, then solve once. Route C (External LUT, profile postExposure = 0): same formula, b = 0 -- tick
//   'routeC' when the builder's Route C is active and CurrentBase() returns 0.
//   v2.1 events (table B3): U6k break-out 0.102, U9 tube flash 0.062, FLASH_TEAR 0.306, F2h water entry EXPO_DOWN
//   0.154-0.156, exit to dusk: pin with EXPO_DOWN ~0.68 then release on one EV-linear line to EXPO_UP ~0.11 at F9,
//   mirror pulses 0.095, white crash / swell 0.270 / 0.649, after the whites 0.241 / 0.200. The galaxy ignition
//   (F13) is NOT an exposure event any more (light-source gain curve).
//
// SCENE VOLUMES ARE DRIVEN BY WEIGHT ONLY. CurrentBase() skips a scene volume whose GameObject is inactive (PPv2
// skips it too), but it cannot see the PostProcessVolume component's own 'enabled' flag: never toggle that.
//
// HOW TO USE
//   Put this component on the "Lanbai_Grades" root that LanbaiGradeBuilder creates; it wires itself by
//   name in Start (Scenes/PPV_<id>, Helpers/PPV_EXPO_UP, Helpers/PPV_EXPO_DOWN, Lens_DesktopOnly).
//   Static (no instance needed):   float w = LanbaiExposure.WeightUp(dEV, b);
//   Instance (does it all):        float applied = exposure.SetDeltaEV(dEV);   // reads b from the volumes
//                                  overlayMat.SetColor(..., fill * LanbaiExposure.OverlayFillScale(applied));
//
// FALLBACK (only if your SDK's Class Exposure Tree has no PostProcessVolume.weight):
//   add the scripting define LANBAI_PPV_ANIMATOR_FALLBACK and run 蓝白/Grades/Fallback/Add Animator
//   Weight Drivers. Every volume then gets an Animator whose float "w" drives PostProcessVolume.weight,
//   and this script talks to the Animators instead (no PostProcessVolume type is referenced at all).

