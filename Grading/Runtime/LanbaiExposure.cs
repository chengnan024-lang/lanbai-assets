    /// <summary>Find the volumes by name under this GameObject (the Lanbai_Grades root). Safe to call again.</summary>
    public void Wire()
    {
        Transform scenes = transform.Find("Scenes");
        if (_sceneGo == null || _sceneGo.Length != SceneCount) _sceneGo = new GameObject[SceneCount];
        for (int i = 0; i < SceneCount; i++)
        {
            if (scenes == null) break;
            Transform t = scenes.Find("PPV_" + SceneId(i));
            if (t == null)
            {
                if (GetSceneVolumeRaw(i) == null) Debug.LogWarning("[LanbaiExposure] missing scene volume Scenes/PPV_" + SceneId(i));
                continue;
            }
            _sceneGo[i] = t.gameObject;
            if (GetSceneVolumeRaw(i) == null) SetSceneVolumeRaw(i, ResolveVolume(t));
        }
        if (scenes == null) Debug.LogWarning("[LanbaiExposure] no child 'Scenes': put this component on the Lanbai_Grades root");

        if (expoUp == null)
        {
            Transform t = transform.Find("Helpers/PPV_EXPO_UP");
            if (t != null) expoUp = ResolveVolume(t);
        }
        if (expoDown == null)
        {
            Transform t = transform.Find("Helpers/PPV_EXPO_DOWN");
            if (t != null) expoDown = ResolveVolume(t);
        }
        if (whiteSat == null)
        {
            Transform t = transform.Find("Helpers/PPV_WHITE_SAT");
            if (t != null) whiteSat = ResolveVolume(t);
        }
        if (whiteBloom == null)
        {
            Transform t = transform.Find("Helpers/PPV_WHITE_BLOOM");
            if (t != null) whiteBloom = ResolveVolume(t);
        }
        if (lensClean == null)
        {
            Transform t = transform.Find("Lens_DesktopOnly/PPV_LENS_CLEAN");
            if (t != null) lensClean = ResolveVolume(t);
        }
        if (lensArchive == null)
        {
            Transform t = transform.Find("Lens_DesktopOnly/PPV_LENS_ARCHIVE");
            if (t != null) lensArchive = ResolveVolume(t);
        }
        if (lensRoot == null)
        {
            Transform t = transform.Find("Lens_DesktopOnly");
            if (t != null) lensRoot = t.gameObject;
        }
        if (expoUp == null || expoDown == null) Debug.LogWarning("[LanbaiExposure] EXPO_UP / EXPO_DOWN volumes not found");
        _wired = true;
    }

    /// <summary>Bible 1.4: in VR the desktop lens layers (vignette + grain) are switched off at start.</summary>
    public void ApplyVRLensRule()
    {
        if (lensRoot == null) return;
        VRCPlayerApi lp = Networking.LocalPlayer;
        if (!Utilities.IsValid(lp)) return;
        if (lp.IsUserInVR()) lensRoot.SetActive(false);
    }

    /// <summary>Set a scene volume's weight (index = SceneId order). Crossfade rule: raise the new one while the old stays at 1.</summary>
    public void SetSceneWeight(int sceneIndex, float weight)
    {
        if (!_wired) Wire();
        var v = GetSceneVolumeRaw(sceneIndex);
        if (v == null) return;
        WriteWeight(v, weight);
    }

    public float GetSceneWeight(int sceneIndex)
    {
        if (!_wired) Wire();
        var v = GetSceneVolumeRaw(sceneIndex);
        if (v == null) return 0f;
        return ReadWeight(v);
    }

    /// <summary>
    /// b: the postExposure the scene volumes blend to right now (PPv2 fold over the live weights). 0 in Route C.
    /// A scene volume whose GameObject is inactive is skipped, as PPv2 skips it (verify.md m5).
    /// </summary>
    public float CurrentBase()
    {
        if (!_wired) Wire();
        if (routeC) return 0f;
        float pe = 0f;
        for (int i = 0; i < SceneCount; i++)
        {
            var v = GetSceneVolumeRaw(i);
            if (v == null) continue;
            if (_sceneGo != null && _sceneGo[i] != null && !_sceneGo[i].activeInHierarchy) continue;
            float w = Mathf.Clamp01(ReadWeight(v));
            if (w > 0f) pe = pe + (ScenePostExposure(i) - pe) * w;
        }
        return pe;
    }

    /// <summary>
    /// Apply this frame's summed exposure offset (EV). Reads b from the live scene weights, writes
    /// EXPO_UP / EXPO_DOWN (the unused one goes to 0) and returns the EV actually applied (clamped
    /// when dEV would need a weight above 1). Call AFTER the frame's scene-weight changes.
    /// </summary>
    public float SetDeltaEV(float deltaEV)
    {
        return SetDeltaEVWithBase(deltaEV, CurrentBase());
    }

    /// <summary>Same with an explicit base (Route C: b = 0; or when the Director already knows b).</summary>
    public float SetDeltaEVWithBase(float deltaEV, float baseEV)
    {
        if (!_wired) Wire();
        float wUp = WeightUp(deltaEV, baseEV);
        float wDown = WeightDown(deltaEV, baseEV);
        if (expoUp != null) WriteWeight(expoUp, wUp);
        if (expoDown != null) WriteWeight(expoDown, wDown);
        _requestedDeltaEV = deltaEV;
        _lastBase = baseEV;
        _appliedDeltaEV = AppliedDeltaEV(wUp, wDown, baseEV);
        return _appliedDeltaEV;
    }

    /// <summary>Both exposure helpers to 0 (e.g. the frame the overlay is full and the grade hard-cuts).</summary>
    public void ClearDeltaEV()
    {
        SetDeltaEVWithBase(0f, 0f);
    }

