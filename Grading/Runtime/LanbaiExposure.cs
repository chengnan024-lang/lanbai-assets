    /// <summary>EXPO_UP weight for +dEV on top of base b: w = dEV / (4 - b). 0 when dEV &lt;= 0.</summary>
    public static float WeightUp(float deltaEV, float baseEV)
    {
        float span = ExpoUpTarget - baseEV;
        if (deltaEV <= 0f || span <= 0f) return 0f;
        return Mathf.Clamp01(deltaEV / span);
    }

    /// <summary>EXPO_DOWN weight for -|dEV| on top of base b: w = -dEV / (b + 4). 0 when dEV &gt;= 0.</summary>
    public static float WeightDown(float deltaEV, float baseEV)
    {
        float span = baseEV - ExpoDownTarget;
        if (deltaEV >= 0f || span <= 0f) return 0f;
        return Mathf.Clamp01(-deltaEV / span);
    }

    /// <summary>The EV actually added by EXPO_UP at weight wUp and EXPO_DOWN at wDown (use only one of them).</summary>
    public static float AppliedDeltaEV(float wUp, float wDown, float baseEV)
    {
        return wUp * (ExpoUpTarget - baseEV) - wDown * (baseEV - ExpoDownTarget);
    }

    /// <summary>
    /// PPv2 fold of the scene volumes' postExposure: start at 0 EV (PPv2 default), then for every scene
    /// volume in ascending priority, pe = lerp(pe, pe_i, w_i). sceneWeights[i] = weight of scene i
    /// (index order = SceneId order = priority order).
    /// </summary>
    public static float BlendedBase(float[] sceneWeights)
    {
        float pe = 0f;
        if (sceneWeights == null) return pe;
        int n = sceneWeights.Length;
        if (n > SceneCount) n = SceneCount;
        for (int i = 0; i < n; i++)
        {
            float w = Mathf.Clamp01(sceneWeights[i]);
            if (w > 0f) pe = pe + (ScenePostExposure(i) - pe) * w;
        }
        return pe;
    }

    /// <summary>Bible 1.4 shortcut for a standard crossfade (old at weight 1, new rising): b = lerp(pe_old, pe_new, w_new).</summary>
    public static float CrossfadeBase(int oldIndex, int newIndex, float newWeight)
    {
        float a = ScenePostExposure(oldIndex);
        return a + (ScenePostExposure(newIndex) - a) * Mathf.Clamp01(newWeight);
    }

    /// <summary>Overlay-sphere compensation (bible 1.8 / calib §D): fill_live = fill × 2^(−dEV_applied).</summary>
    public static float OverlayFillScale(float appliedDeltaEV)
    {
        return Mathf.Pow(2f, -appliedDeltaEV);
    }

    /// <summary>
    /// Route C only (External LUTs blend in display-linear light): weight for an exposure-changing
    /// crossfade so it still reads EV-linear. x = 0..1 normalised time. w = (2^(dEV·x) − 1) / (2^dEV − 1).
    /// </summary>
    public static float RouteCCrossfadeWeight(float deltaEV, float x)
    {
        x = Mathf.Clamp01(x);
        if (Mathf.Abs(deltaEV) < 0.0001f) return x;
        return (Mathf.Pow(2f, deltaEV * x) - 1f) / (Mathf.Pow(2f, deltaEV) - 1f);
    }

