# -*- coding: utf-8 -*-
"""Generate Common/Shaders/LanbaiGlobals.cginc from the registry (Common/UdonGlobals.md on origin/main): every registered
_Udon_ global declared ONCE, each behind its own guard, so any number of includes can declare the same name safely.

  python3 Common/Tools~/globals/gen_globals.py [--out Common/Shaders/LanbaiGlobals.cginc] [--fetch]

HLSL type of each name: taken from the declarations that already exist in main and every pkg/* branch (if they disagree the
generator stops and lists them: fix the registry / the shaders first); names never declared in HLSL get the type the
registry row states (float / float4 / texture words), else float4. Textures: samplerCUBE for *Cube*, sampler2D otherwise.
Proposal (Engineering/给总导演.md 2026-10-23); the output location / owner is the director's call."""
import argparse
import collections
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, '..', '..', '..'))
sys.path.insert(0, os.path.join(REPO, 'Engineering', 'ledgers'))
import globals_scan as GS  # noqa: E402

# types stated in the owning package's interface document where no shader declares the name yet (source in the comment)
KNOWN = {'_Udon_SeaLevel': 'float', '_Udon_SeaMode': 'float',          # Sea/README_Sea接口.md §3 (pkg/sea)
         '_Udon_SeaClock': 'float4', '_Udon_Caustics': 'float4', '_Udon_CausticsColor': 'float4',   # same
         '_Udon_MirrorPlane': 'float4', '_Udon_MirrorRimLight': 'float4',                          # Mirrors/给总控.md
         '_Udon_WorldS': 'float', '_Udon_T': 'float'}                                              # LB_Journey (local)
NORM = {'half': 'float', 'half2': 'float2', 'half3': 'float3', 'half4': 'float4', 'fixed4': 'float4', 'fixed': 'float'}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default=None)
    ap.add_argument('--fetch', action='store_true')
    a = ap.parse_args()
    if a.fetch:
        GS.git('fetch', '-q', 'origin')
    reg, reserved = GS.registry()
    refs = ['origin/main'] + sorted(r.strip() for r in GS.git('branch', '-r').splitlines() if 'origin/pkg/' in r)
    types = collections.defaultdict(set)
    where = collections.defaultdict(list)
    for r in refs:
        for n, uses in GS.scan(r).items():
            for f, kind, ty in uses:
                if kind == 'decl' and ty:
                    t = NORM.get(ty, ty)
                    if t.startswith('UNITY_DECLARE_TEXCUBE') or t == 'TextureCube':
                        t = 'samplerCUBE'
                    if t in ('UNITY_DECLARE_TEX2D', 'Texture2D'):
                        t = 'sampler2D'
                    types[n].add(t)
                    where[n].append('%s:%s' % (r.replace('origin/', ''), f))
    md = GS.git('show', 'origin/main:Common/UdonGlobals.md')
    rowtext = {}
    for line in md.splitlines():
        for n in GS.NAME.findall(line.split('|')[1] if line.startswith('|') and line.count('|') > 2 else ''):
            rowtext.setdefault(n, line)
    clash = {n: t for n, t in types.items() if len(t) > 1}
    if clash:
        for n, t in sorted(clash.items()):
            print('TYPE CLASH %s: %s  (%s)' % (n, ' / '.join(sorted(t)), '; '.join(where[n][:6])))
        sys.exit(1)
    out = ['// =====================================================================================================',
           '//  Lanbai / LanbaiGlobals.cginc   GENERATED by Common/Tools~/globals/gen_globals.py from Common/UdonGlobals.md',
           '//  Every registered _Udon_ global, declared once, each behind its own guard: include this instead of declaring',
           '//  _Udon_ names yourself (a second declaration of the same uniform is FXC error X3003). Do not edit by hand.',
           '//  !!! WRITTEN WITHOUT A UNITY COMPILER; checked with Common/Tools~/compile_check (DXC + Unity CGIncludes). !!!',
           '// =====================================================================================================',
           '#ifndef LANBAI_GLOBALS_INCLUDED', '#define LANBAI_GLOBALS_INCLUDED', '']
    star = set(re.findall(r'`(_Udon_\w+?)\*`', md))                                # `_Udon_Sky_*` is a family, not a name
    names = set(n for n in reg if n not in star)
    for pre in star:                                   # a family = every name with that prefix declared in any shader
        fam = [n for n in types if n.startswith(pre)]
        names |= set(fam)
        if fam:
            print('family %s*: %d names from shader declarations' % (pre, len(fam)))
    names = sorted(names)
    unresolved = []
    for n in names:
        stated = re.search(r'`%s`[^|]*\|\s*(float4|float3|float2|float)\b' % re.escape(n), rowtext.get(n, ''))
        pass
        sib = re.sub(r'\d+$', '', n)
        sib_t = {next(iter(types[k])) for k in types if re.sub(r'\d+$', '', k) == sib and k != n and re.search(r'\d$', k)}
        if n in types:
            t = next(iter(types[n]))
            if stated and stated.group(1) != t:
                unresolved.append((n, 'registry says %s, shaders declare %s' % (stated.group(1), t)))
                continue
        elif n in KNOWN:
            t = KNOWN[n]
        elif stated:
            t = stated.group(1)
        elif re.search(r'\d$', n) and len(sib_t) == 1:
            t = next(iter(sib_t))                          # _Udon_Lamp3 = the type of the declared _Udon_Lamp0
        else:
            unresolved.append((n, rowtext.get(n, '').strip()[:160]))      # D-32 #1: never guess a type
            continue
        tag = (' // reserved' if n in reserved else '') + ''
        out += ['#ifndef LANBAI_DECL_%s' % n, '#define LANBAI_DECL_%s' % n, '%s %s;%s' % (t, n, tag), '#endif']
    if unresolved:
        print('NO TYPE for %d registered name(s): declare it in a shader, or write its type in the registry row '
              '(`_Udon_X` | float4 | ...), or add it to KNOWN. Nothing written.' % len(unresolved))
        for n, row in unresolved:
            print('  %s    <- %s' % (n, row))
        sys.exit(2)
    out += ['', '#endif // LANBAI_GLOBALS_INCLUDED', '']
    txt = '\n'.join(out)
    if a.out:
        open(a.out, 'w', encoding='utf-8').write(txt)
        print('wrote %s (%d globals, every type from a declaration, the registry or KNOWN; none guessed)' % (a.out, len(names)))
    else:
        sys.stdout.write(txt)


if __name__ == '__main__':
    main()
