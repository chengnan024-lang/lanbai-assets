#!/usr/bin/env python3
"""
Lanbai / 蓝白 : cabin tube flicker schedule for scene 4 (the tentacle gate).

Generates a deterministic, photosensitivity-safe schedule of tube "dips" and exports it as
  - out/flicker_schedule.json
  - out/FlickerTable.cs   (UdonSharp-ready float/int arrays to paste into the Director)

Safety is by construction, then re-checked:
  * every dip is ONE flash (one down + one up transition); no multi-blink bursts;
  * the start of any two dips (any tubes) are >= MIN_GAP s apart  ->  at most 2 flashes in any 1 s window
    (WCAG 2.3.1 allows 3; we keep one flash of margin because VR tubes fill a large part of the field);
  * nothing happens in the QUIET s before the entry, so the entry flash stands alone;
  * a "companion" tube (the 30 % neighbour correlation asked by look-dev) dips with the SAME start and
    SAME duration, so the pair is still a single flash.
A continuous sub-threshold shimmer (<= +-6 % of the tube level, <= 2 Hz) is NOT in this table: it lives in
the tube shader and never qualifies as a flash (change < 10 % of max relative luminance).

Times are in seconds RELATIVE TO THE ENTRY CUE ("Gott"), i.e. negative. The Director converts:
  t_rel = musicTime - T_GOTT.
"""
import json, math, os, sys
import numpy as np

SEED = 20260928
N_TUBES = 10            # 2 rows x 5, index = row*5 + col, col 0 = front
T_START = -105.0        # the tear reveal (value score: 3:15 -> 5:00)
QUIET = 1.5             # no dips in the last 1.5 s before the entry flash
MIN_GAP = 0.60          # s between dip starts (any tubes): 2*0.60 >= 1 s + longest dip -> <= 4 transitions (2 flashes) in any 1 s
DUR = (0.07, 0.15)      # dip duration (s): 6..14 frames at 90 Hz; never a single-frame blink
RATE0, RATE1 = 0.10, 1.6  # dips per second at the reveal -> near the entry (exponential ramp)
DEPTH_EARLY = (0.25, 0.45)  # tube level during a dip, early (0 = dark, 1 = normal)
DEPTH_LATE = (0.03, 0.20)   # ... near the entry
P_COMPANION = 0.30

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "out")


def rate(t):
    x = (t - T_START) / (-QUIET - T_START)
    x = min(max(x, 0.0), 1.0)
    return RATE0 * (RATE1 / RATE0) ** (x ** 1.6)   # stays sparse for a long time, then climbs


def make(seed=SEED):
    rng = np.random.default_rng(seed)
    t = T_START + 2.0
    events = []
    last_tube = -1
    while True:
        # renewal process with a hard refractory period: gap = MIN_GAP + Exp(mean = 1/rate - MIN_GAP)
        mean_extra = max(1.0 / rate(t) - MIN_GAP, 0.02)
        t += MIN_GAP + rng.exponential(mean_extra)
        if t >= -QUIET:
            break
        x = (t - T_START) / (-QUIET - T_START)
        lo = DEPTH_EARLY[0] + (DEPTH_LATE[0] - DEPTH_EARLY[0]) * x
        hi = DEPTH_EARLY[1] + (DEPTH_LATE[1] - DEPTH_EARLY[1]) * x
        depth = float(rng.uniform(lo, hi))
        dur = float(rng.uniform(*DUR))
        # the rear tubes fail more often (they are "older"); avoid the same tube twice in a row
        w = np.array([1.0, 1.1, 1.2, 1.4, 1.8] * 2)
        if last_tube >= 0:
            w[last_tube] = 0.2
        tube = int(rng.choice(N_TUBES, p=w / w.sum()))
        mask = 1 << tube
        if rng.random() < P_COMPANION:
            row, col = divmod(tube, 5)
            nb = [row * 5 + c for c in (col - 1, col + 1) if 0 <= c < 5]
            mask |= 1 << int(rng.choice(nb))
        events.append({"t": round(float(t), 3), "dur": round(dur, 3), "level": round(depth, 3), "mask": int(mask)})
        last_tube = tube
    return events


def check(events):
    ts = np.array([e["t"] for e in events])
    gaps = np.diff(ts)
    # max number of dip starts in any 1 s window
    mx = 0
    for i, t0 in enumerate(ts):
        mx = max(mx, int(np.sum((ts >= t0) & (ts < t0 + 1.0))))
    return {
        "n_dips": len(events),
        "min_gap_s": float(gaps.min()) if len(gaps) else None,
        "max_flashes_in_any_1s": mx,
        "last_dip_end_before_entry_s": float(-(ts[-1] + events[-1]["dur"])),
        "dips_last_20s": int(np.sum(ts > -20)),
        "dips_first_60s": int(np.sum(ts < T_START + 60)),
    }


def level_at(events, t, n=N_TUBES):
    """Tube levels (0..1) at relative time t, for simulation/preview."""
    lv = np.ones(n)
    for e in events:
        if e["t"] <= t < e["t"] + e["dur"]:
            for i in range(n):
                if e["mask"] >> i & 1:
                    lv[i] = min(lv[i], e["level"])
    return lv


def export_cs(events, path):
    f = lambda xs: ", ".join(f"{x:.3f}f" for x in xs)
    lines = [
        "// Lanbai / 蓝白  -  scene 4 cabin tube flicker table (generated by art/lens_tech/flicker_schedule.py; do not hand-edit)",
        f"// seed {SEED}; {len(events)} dips; min gap {MIN_GAP}s between dip starts => <= 2 flashes in any 1 s; quiet {QUIET}s before the entry.",
        "// Checked by art/lens_tech/flashcheck.py (synthetic seat view): WCAG 2.3.1 PASS, Lanbai <= 2 flashes/s PASS.",
        "// t = seconds relative to the entry cue (\"Gott\"), negative. mask bit i = tube i (row*5+col, col 0 = front).",
        "// level = tube level during the dip (multiply emission AND the tube's share of _Udon_CabinLightmap).",
        f"private float[] _dipT = new float[] {{ {f([e['t'] for e in events])} }};",
        f"private float[] _dipDur = new float[] {{ {f([e['dur'] for e in events])} }};",
        f"private float[] _dipLevel = new float[] {{ {f([e['level'] for e in events])} }};",
        f"private int[] _dipMask = new int[] {{ {', '.join(str(e['mask']) for e in events)} }};",
    ]
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    ev = make()
    stats = check(ev)
    assert stats["max_flashes_in_any_1s"] <= 2, stats
    assert stats["min_gap_s"] >= MIN_GAP - 1e-6, stats
    assert stats["last_dip_end_before_entry_s"] >= QUIET - 0.2, stats
    with open(os.path.join(OUT, "flicker_schedule.json"), "w") as fh:
        json.dump({"params": {"seed": SEED, "tubes": N_TUBES, "t_start": T_START, "quiet": QUIET,
                              "min_gap": MIN_GAP, "dur": DUR, "rate": [RATE0, RATE1]},
                   "stats": stats, "events": ev}, fh, indent=1)
    export_cs(ev, os.path.join(OUT, "FlickerTable.cs"))
    print(json.dumps(stats, indent=1))
